/* Небольшие вспомогательные компоненты для тезисной вёрстки */
function Card({ title, children }) {
  return (
    <div className="card">
      <h2 className="font-display text-lg font-semibold text-cream mb-4">{title}</h2>
      {children}
    </div>
  )
}

function Table({ head, rows }) {
  return (
    <table className="w-full">
      <thead>
        <tr className="text-left">
          {head.map((h, i) => (
            <th
              key={i}
              className={`text-muted text-xs uppercase tracking-widest pb-3 font-body ${
                i === head.length - 1 && head.length > 2 ? '' : ''
              }`}
            >
              {h}
            </th>
          ))}
        </tr>
      </thead>
      <tbody>
        {rows.map((r, ri) => (
          <tr key={ri} className="table-row">
            {r.map((c, ci) => (
              <td
                key={ci}
                className={`py-3 pr-6 text-sm font-body align-top ${
                  ci === 0 ? 'text-cream whitespace-nowrap' : 'text-muted'
                }`}
              >
                {ci === 0 ? (
                  <span className="badge bg-gold/10 text-gold border border-gold/20 font-mono">{c}</span>
                ) : (
                  c
                )}
              </td>
            ))}
          </tr>
        ))}
      </tbody>
    </table>
  )
}

function Bullets({ items }) {
  return (
    <ul className="space-y-2">
      {items.map((t, i) => (
        <li key={i} className="flex gap-3 text-sm font-body text-muted">
          <span className="text-gold mt-0.5">•</span>
          <span>{t}</span>
        </li>
      ))}
    </ul>
  )
}

