BEGIN;

-- gen_random_uuid() встроен в PostgreSQL 13+. pgcrypto добавляем на случай
-- совместимости со старыми клиентами / дополнительной криптографии.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ---------------------------------------------------------------------
-- Справочники верхнего уровня
-- ---------------------------------------------------------------------

CREATE TABLE material_categories (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name        text NOT NULL,
    description text,
    created_at  timestamptz DEFAULT now()
);

CREATE TABLE product_types (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL,
    sort_order integer NOT NULL DEFAULT 100,
    code       text UNIQUE,
    parent_id  integer REFERENCES product_types(id)
);

CREATE TABLE clients (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name       text NOT NULL,
    notes      text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE assortments (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    code        text NOT NULL UNIQUE,
    name        text NOT NULL,
    description text,
    created_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Сырьё и цены
-- ---------------------------------------------------------------------

CREATE TABLE raw_materials (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name        text NOT NULL,
    category_id uuid REFERENCES material_categories(id),
    unit        text NOT NULL DEFAULT 'кг',
    description text,
    supplier    text,
    is_active   boolean DEFAULT true,
    created_at  timestamptz DEFAULT now(),
    updated_at  timestamptz DEFAULT now(),
    article     text UNIQUE
);

CREATE TABLE material_prices (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    material_id    uuid NOT NULL REFERENCES raw_materials(id),
    price_per_unit numeric NOT NULL,
    valid_from     date NOT NULL DEFAULT CURRENT_DATE,
    valid_to       date,
    supplier       text,
    notes          text,
    created_at     timestamptz DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Рецепты (купажи) и их состав
-- ---------------------------------------------------------------------

CREATE TABLE recipes (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name            text NOT NULL,
    description     text,
    output_quantity numeric NOT NULL DEFAULT 1,
    output_unit     text NOT NULL DEFAULT 'кг',
    notes           text,
    is_active       boolean DEFAULT true,
    created_at      timestamptz DEFAULT now(),
    updated_at      timestamptz DEFAULT now(),
    article         text UNIQUE,
    photo_url       text
);

CREATE TABLE recipe_ingredients (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    recipe_id     uuid NOT NULL REFERENCES recipes(id),
    material_id   uuid REFERENCES raw_materials(id),
    quantity      numeric NOT NULL,
    unit          text NOT NULL DEFAULT 'кг',
    notes         text,
    created_at    timestamptz DEFAULT now(),
    sub_recipe_id uuid REFERENCES recipes(id)
);

-- ---------------------------------------------------------------------
-- SKU (товары), их состав и описания
-- ---------------------------------------------------------------------

CREATE TABLE products (
    id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name         text NOT NULL,
    recipe_id    uuid REFERENCES recipes(id),
    package_size numeric,
    package_unit text DEFAULT 'г',
    description  text,
    is_active    boolean DEFAULT true,
    created_at   timestamptz DEFAULT now(),
    updated_at   timestamptz DEFAULT now(),
    article      text UNIQUE,
    type_id      integer REFERENCES product_types(id),
    photo_url    text
);

CREATE TABLE sku_recipe_components (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    product_id  uuid NOT NULL REFERENCES products(id),
    recipe_id   uuid REFERENCES recipes(id),
    material_id uuid REFERENCES raw_materials(id),
    quantity    numeric NOT NULL,
    unit        text NOT NULL DEFAULT 'г',
    notes       text,
    created_at  timestamptz DEFAULT now()
);

CREATE TABLE product_descriptions (
    id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    product_id   uuid NOT NULL UNIQUE REFERENCES products(id),
    description  text,
    generated_at timestamptz,
    updated_at   timestamptz DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Прайслисты (внутренние)
-- ---------------------------------------------------------------------

CREATE TABLE price_lists (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name           text NOT NULL,
    description    text,
    markup_percent numeric DEFAULT 0,
    is_active      boolean DEFAULT true,
    created_at     timestamptz DEFAULT now()
);

CREATE TABLE price_list_items (
    id                     uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    price_list_id          uuid NOT NULL REFERENCES price_lists(id),
    product_id             uuid NOT NULL REFERENCES products(id),
    price                  numeric,
    override_markup_percent numeric,
    created_at             timestamptz DEFAULT now(),
    updated_at             timestamptz DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Ассортименты (связи many-to-many)
-- ---------------------------------------------------------------------

CREATE TABLE assortment_products (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    assortment_id uuid NOT NULL REFERENCES assortments(id),
    product_id    uuid NOT NULL REFERENCES products(id),
    added_at      timestamptz NOT NULL DEFAULT now(),
    notes         text,
    client_id     uuid REFERENCES clients(id),
    UNIQUE (assortment_id, product_id)
);

CREATE TABLE assortment_recipes (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    assortment_id uuid NOT NULL REFERENCES assortments(id),
    recipe_id     uuid NOT NULL REFERENCES recipes(id),
    added_at      timestamptz NOT NULL DEFAULT now(),
    notes         text,
    UNIQUE (assortment_id, recipe_id)
);

CREATE TABLE assortment_price_lists (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    assortment_id uuid NOT NULL REFERENCES assortments(id),
    price_list_id uuid NOT NULL REFERENCES price_lists(id),
    added_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (assortment_id, price_list_id)
);

CREATE TABLE assortment_materials (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    assortment_id uuid NOT NULL REFERENCES assortments(id),
    material_id   uuid NOT NULL REFERENCES raw_materials(id),
    added_at      timestamptz NOT NULL DEFAULT now(),
    notes         text,
    UNIQUE (assortment_id, material_id)
);

-- ---------------------------------------------------------------------
-- Конструктор (проекты)
-- ---------------------------------------------------------------------

CREATE TABLE projects (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    type           text NOT NULL CHECK (type = ANY (ARRAY['recipe','sku'])),
    name           text NOT NULL,
    notes          text,
    created_at     timestamptz NOT NULL DEFAULT now(),
    linked_id      uuid,
    linked_article text,
    linked_name    text
);

CREATE TABLE project_items (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    project_id uuid NOT NULL REFERENCES projects(id),
    material_id uuid REFERENCES raw_materials(id),
    quantity   numeric NOT NULL DEFAULT 0,
    unit       text NOT NULL DEFAULT 'г',
    created_at timestamptz NOT NULL DEFAULT now(),
    recipe_id  uuid REFERENCES recipes(id)
);

