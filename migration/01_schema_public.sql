-- ---------------------------------------------------------------------
-- Расчётные VIEW (себестоимость и ценообразование)
-- Порядок важен: recipe_cost ← sku_cost ← product_pricing/manager_pricelist_v1
-- ---------------------------------------------------------------------

CREATE VIEW raw_materials_with_price AS
 SELECT rm.id, rm.article, rm.name, rm.unit, rm.category_id,
        mp.price_per_unit AS current_price,
        mp.valid_from AS price_date
   FROM raw_materials rm
   LEFT JOIN LATERAL (
        SELECT material_prices.price_per_unit, material_prices.valid_from
          FROM material_prices
         WHERE material_prices.material_id = rm.id
         ORDER BY material_prices.valid_from DESC
         LIMIT 1) mp ON true;

CREATE VIEW recipe_cost AS
 WITH RECURSIVE recipe_tree AS (
         SELECT ri.recipe_id, ri.material_id, ri.sub_recipe_id,
                ri.quantity::numeric AS qty_multiplier
           FROM recipe_ingredients ri
        UNION ALL
         SELECT rt_1.recipe_id, ri2.material_id, ri2.sub_recipe_id,
                rt_1.qty_multiplier * ri2.quantity::numeric AS qty_multiplier
           FROM recipe_tree rt_1
           JOIN recipe_ingredients ri2 ON ri2.recipe_id = rt_1.sub_recipe_id
          WHERE rt_1.sub_recipe_id IS NOT NULL
        )
 SELECT r.id AS recipe_id, r.article AS recipe_article, r.name AS recipe_name,
        r.output_quantity, r.output_unit,
        sum(rt.qty_multiplier * COALESCE((
              SELECT mp.price_per_unit FROM material_prices mp
               WHERE mp.material_id = rt.material_id
                 AND mp.valid_from <= CURRENT_DATE
                 AND (mp.valid_to IS NULL OR mp.valid_to >= CURRENT_DATE)
               ORDER BY mp.valid_from DESC LIMIT 1), 0::numeric)) AS total_cost,
        sum(rt.qty_multiplier * COALESCE((
              SELECT mp.price_per_unit FROM material_prices mp
               WHERE mp.material_id = rt.material_id
                 AND mp.valid_from <= CURRENT_DATE
                 AND (mp.valid_to IS NULL OR mp.valid_to >= CURRENT_DATE)
               ORDER BY mp.valid_from DESC LIMIT 1), 0::numeric))
          / NULLIF(r.output_quantity, 0::numeric) AS cost_per_kg
   FROM recipes r
   JOIN recipe_tree rt ON rt.recipe_id = r.id
  WHERE rt.material_id IS NOT NULL
  GROUP BY r.id, r.article, r.name, r.output_quantity, r.output_unit;

CREATE VIEW sku_cost AS
 SELECT p.id AS product_id, p.article AS sku_article, p.name AS product_name,
        p.package_size, p.package_unit,
        COALESCE(sum(CASE WHEN src.recipe_id IS NOT NULL
             THEN src.quantity * ((SELECT rc.cost_per_kg FROM recipe_cost rc WHERE rc.recipe_id = src.recipe_id))
             ELSE NULL::numeric END), 0::numeric) AS blend_cost,
        COALESCE(sum(CASE WHEN src.material_id IS NOT NULL
             THEN src.quantity * COALESCE((SELECT mp.price_per_unit FROM material_prices mp
                    WHERE mp.material_id = src.material_id
                      AND mp.valid_from <= CURRENT_DATE
                      AND (mp.valid_to IS NULL OR mp.valid_to >= CURRENT_DATE)
                    ORDER BY mp.valid_from DESC LIMIT 1), 0::numeric)
             ELSE NULL::numeric END), 0::numeric) AS packaging_cost,
        COALESCE(sum(CASE WHEN src.recipe_id IS NOT NULL
             THEN src.quantity * ((SELECT rc.cost_per_kg FROM recipe_cost rc WHERE rc.recipe_id = src.recipe_id))
             ELSE NULL::numeric END), 0::numeric)
        + COALESCE(sum(CASE WHEN src.material_id IS NOT NULL
             THEN src.quantity * COALESCE((SELECT mp.price_per_unit FROM material_prices mp
                    WHERE mp.material_id = src.material_id
                      AND mp.valid_from <= CURRENT_DATE
                      AND (mp.valid_to IS NULL OR mp.valid_to >= CURRENT_DATE)
                    ORDER BY mp.valid_from DESC LIMIT 1), 0::numeric)
             ELSE NULL::numeric END), 0::numeric) AS total_sku_cost
   FROM products p
   JOIN sku_recipe_components src ON src.product_id = p.id
  GROUP BY p.id, p.article, p.name, p.package_size, p.package_unit;

CREATE VIEW product_pricing AS
 SELECT p.id AS product_id, p.article AS sku_article, p.name AS product_name,
        p.package_size, p.package_unit, sc.total_sku_cost,
        pl.id AS price_list_id, pl.name AS price_list_name,
        COALESCE(pli.override_markup_percent, pl.markup_percent) AS markup_percent,
        COALESCE(pli.price, round(sc.total_sku_cost * (1::numeric + COALESCE(pli.override_markup_percent, pl.markup_percent) / 100::numeric), 2)) AS final_price
   FROM products p
   JOIN sku_cost sc ON sc.product_id = p.id
   CROSS JOIN price_lists pl
   LEFT JOIN price_list_items pli ON pli.product_id = p.id AND pli.price_list_id = pl.id;

-- Изолированный прайс для менеджеров: 5 уровней цен без НДС, без себестоимости.
CREATE VIEW manager_pricelist_v1 AS
 SELECT p.id AS product_id, p.article AS sku_article, p.name AS sku_name,
        p.photo_url, p.package_size, p.package_unit, pt.name AS category_name,
        round(sc.total_sku_cost * 2.70)::integer AS price_base,
        round(sc.total_sku_cost * 2.50)::integer AS price_opt,
        round(sc.total_sku_cost * 2.30)::integer AS price_opt_plus,
        round(sc.total_sku_cost * 2.10)::integer AS price_partner,
        round(sc.total_sku_cost * 1.95)::integer AS price_key_partner
   FROM products p
   LEFT JOIN product_types pt ON pt.id = p.type_id
   LEFT JOIN sku_cost sc ON sc.product_id = p.id
  WHERE p.is_active = true AND sc.total_sku_cost IS NOT NULL;

-- ---------------------------------------------------------------------
-- Триггеры автоматического наполнения ассортиментов
-- (чистая бизнес-логика, переносится как есть)
-- ---------------------------------------------------------------------

CREATE OR REPLACE FUNCTION trg_material_to_all_assortments()
 RETURNS trigger LANGUAGE plpgsql AS $function$
BEGIN
  INSERT INTO assortment_materials (assortment_id, material_id)
  SELECT a.id, NEW.id FROM assortments a
  WHERE NOT EXISTS (
    SELECT 1 FROM assortment_materials am
    WHERE am.assortment_id = a.id AND am.material_id = NEW.id);
  RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION trg_assortment_gets_shared()
 RETURNS trigger LANGUAGE plpgsql AS $function$
BEGIN
  INSERT INTO assortment_materials (assortment_id, material_id)
  SELECT NEW.id, m.id FROM raw_materials m
  WHERE NOT EXISTS (
    SELECT 1 FROM assortment_materials am
    WHERE am.assortment_id = NEW.id AND am.material_id = m.id);
  RETURN NEW;
END;
$function$;

CREATE TRIGGER material_to_all_assortments
  AFTER INSERT ON raw_materials
  FOR EACH ROW EXECUTE FUNCTION trg_material_to_all_assortments();

CREATE TRIGGER assortment_gets_shared
  AFTER INSERT ON assortments
  FOR EACH ROW EXECUTE FUNCTION trg_assortment_gets_shared();

COMMIT;

